def cap(n):
    return n[0].upper() + n[1:]


def codec_type(t):
    return {"int": "Codec.INT", "float": "Codec.FLOAT", "boolean": "Codec.BOOL"}[t]


def main():
    half = 14
    groups = [FIELDS[:half], FIELDS[half:]]
    lines = []
    w = lines.append
    w("// GENERATED by tools/gen_settings.py — edit the generator, not this file.")
    w("package dev.hackdanel.realcamera.component;")
    w("")
    w("import com.mojang.datafixers.util.Pair;")
    w("import com.mojang.serialization.Codec;")
    w("import com.mojang.serialization.MapCodec;")
    w("import com.mojang.serialization.codecs.RecordCodecBuilder;")
    w("import io.netty.buffer.ByteBuf;")
    w("import net.minecraft.network.codec.StreamCodec;")
    w("")
    w("/**")
    w(" * User-facing camera state stored on the camera item (survives being dropped or traded, like a real")
    w(" * camera remembers its dials). Index fields point into {@link dev.hackdanel.realcamera.optics.ExposureScales}:")
    w(" * isoIndex -1 = Auto ISO; evComp is in 1/3 EV; focal 0 = lens minimum; afX/afY are the AF point in")
    w(" * frame coordinates (-1..1).")
    w(" */")
    params = ", ".join(f"{t} {n}" for n, t, _, _ in FIELDS)
    w(f"public record CameraSettings({params}) {{")
    w(CONSTANTS)
    defaults = ", ".join(d for _, _, _, d in FIELDS)
    w(f"    public static final CameraSettings DEFAULT = new CameraSettings({defaults});")
    w("")
    for gi, g in enumerate(groups):
        tparams = ", ".join(("Integer" if t == "int" else "Float" if t == "float" else "Boolean") for _, t, _, _ in g)
        w(f"    private record G{gi}({', '.join(f'{t} {n}' for n, t, _, _ in g)}) {{")
        w(f"        static final MapCodec<G{gi}> CODEC = RecordCodecBuilder.mapCodec(i -> i.group(")
        for k, (n, t, key, d) in enumerate(g):
            sep = "," if k < len(g) - 1 else ""
            w(f"                {codec_type(t)}.optionalFieldOf(\"{key}\", DEFAULT.{n}()).forGetter(G{gi}::{n}){sep}")
        w(f"        ).apply(i, G{gi}::new));")
        w("    }")
        w("")
    a = ", ".join(f"p.getFirst().{n}()" for n, _, _, _ in groups[0])
    b = ", ".join(f"p.getSecond().{n}()" for n, _, _, _ in groups[1])
    ga = ", ".join(f"s.{n}" for n, _, _, _ in groups[0])
    gb = ", ".join(f"s.{n}" for n, _, _, _ in groups[1])
    w("    public static final Codec<CameraSettings> CODEC = Codec.mapPair(G0.CODEC, G1.CODEC).xmap(")
    w(f"            p -> new CameraSettings({a},\n                    {b}),")
    w(f"            s -> Pair.of(new G0({ga}), new G1({gb}))).codec();")
    w("")
    w("    public static final StreamCodec<ByteBuf, CameraSettings> STREAM_CODEC = new StreamCodec<>() {")
    w("        @Override")
    w("        public CameraSettings decode(ByteBuf buf) {")
    reads = []
    for n, t, _, _ in FIELDS:
        reads.append({"int": "buf.readInt()", "float": "buf.readFloat()", "boolean": "buf.readBoolean()"}[t])
    w("            return new CameraSettings(" + ", ".join(reads) + ");")
    w("        }")
    w("")
    w("        @Override")
    w("        public void encode(ByteBuf buf, CameraSettings s) {")
    for n, t, _, _ in FIELDS:
        m = {"int": "writeInt", "float": "writeFloat", "boolean": "writeBoolean"}[t]
        w(f"            buf.{m}(s.{n});")
    w("        }")
    w("    };")
    for n, t, _, _ in FIELDS:
        args = ", ".join("v" if m == n else m for m, _, _, _ in FIELDS)
        w("")
        w(f"    public CameraSettings with{cap(n)}({t} v) {{")
        w(f"        return new CameraSettings({args});")
        w("    }")
    w("")
    w("    // compatibility helpers used across the code base")
    w("    public CameraSettings withShutter(int v) {")
    w("        return withShutterIndex(v);")
    w("    }")
    w("")
    w("    public CameraSettings withAperture(int v) {")
    w("        return withApertureIndex(v);")
    w("    }")
    w("")
    w("    public CameraSettings withIso(int v) {")
    w("        return withIsoIndex(v);")
    w("    }")
    w("")
    w("    public CameraSettings withWhiteBalance(int wb, int k) {")
    w("        return withWhiteBalance(wb).withKelvin(k);")
    w("    }")
    w("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT), len(FIELDS), "fields")


if __name__ == "__main__":
    main()
